"""Build the combined statement dataset for the layer-wise truth probing project.

Reads the English true/false CSVs copied from the Truth is Universal repository
(data/raw/truth_is_universal) and writes:

  data/statements.csv          one row per statement, with type, topic and split group
  data/summary_by_type.csv     counts, balance and length per statement type
  data/summary_by_topic.csv    counts per statement type x topic
  docs/data_summary.md         the same numbers as a readable table

Run from the repository root:  python scripts/build_dataset.py
"""

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw" / "truth_is_universal"
OUT = ROOT / "data"
DOCS = ROOT / "docs"

TOPICS = ["animal_class", "cities", "element_symb", "facts", "inventors", "sp_en_trans"]

# (file stem, statement type, topic)
SOURCES = []
for t in TOPICS:
    SOURCES += [
        (t, "affirmative", t),
        (f"neg_{t}", "negated", t),
        (f"{t}_conj", "conjunction", t),
        (f"{t}_disj", "disjunction", t),
    ]
SOURCES += [
    ("larger_than", "comparison", "numbers"),
    ("smaller_than", "comparison", "numbers"),
]

TYPE_ORDER = ["affirmative", "negated", "conjunction", "disjunction", "comparison"]


def split_group(df: pd.DataFrame, stem: str, stype: str, topic: str) -> pd.Series:
    """Key for grouped train/test splits: statements sharing a key never go to
    different sides of a split.

    - cities / neg_cities: the city, so a city is either seen in training or not.
    - larger_than / smaller_than: the unordered number pair, so "51 is larger than 52"
      and "51 is smaller than 52" stay together.
    - other affirmative / negated sets: the row position. The neg_ files are row-aligned
      with their affirmative files, so a fact and its negation share a key.
    - conjunctions / disjunctions: one key per row.
    """
    if topic == "cities" and "city" in df.columns:
        return "cities:" + df["city"].astype(str)
    if stype == "comparison":
        lo = df[["n1", "n2"]].min(axis=1).astype(str)
        hi = df[["n1", "n2"]].max(axis=1).astype(str)
        return "numbers:" + lo + "-" + hi
    if stype in ("affirmative", "negated"):
        return f"{topic}:" + df.index.astype(str)
    return f"{topic}:{stype}:" + df.index.astype(str)


def main() -> None:
    frames = []
    for stem, stype, topic in SOURCES:
        df = pd.read_csv(RAW / f"{stem}.csv")
        df = df.reset_index(drop=True)
        part = pd.DataFrame(
            {
                "statement": df["statement"].astype(str).str.strip(),
                "label": df["label"].astype(int),
                "type": stype,
                "topic": topic,
                "source_file": f"{stem}.csv",
                "group": split_group(df, stem, stype, topic),
            }
        )
        frames.append(part)

    data = pd.concat(frames, ignore_index=True)
    n_before = len(data)
    data = data.drop_duplicates(subset=["statement", "label"]).reset_index(drop=True)
    # Some source rows carry the same statement with both labels (label noise in the
    # original disjunction and facts files). There is no way to tell which label is
    # right, so every copy of such a statement is removed.
    conflicts = data[data.duplicated(subset=["statement"], keep=False)]
    data = data[~data["statement"].isin(conflicts["statement"])].reset_index(drop=True)
    data["n_words"] = data["statement"].str.split().str.len()
    data["n_chars"] = data["statement"].str.len()
    data.insert(0, "id", range(len(data)))
    data["type"] = pd.Categorical(data["type"], categories=TYPE_ORDER, ordered=True)

    OUT.mkdir(exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    data.to_csv(OUT / "statements.csv", index=False)

    by_type = (
        data.groupby("type", observed=True)
        .agg(
            n=("label", "size"),
            n_true=("label", "sum"),
            share_true=("label", "mean"),
            mean_words=("n_words", "mean"),
            min_words=("n_words", "min"),
            max_words=("n_words", "max"),
            n_topics=("topic", "nunique"),
            n_groups=("group", "nunique"),
        )
        .reset_index()
    )
    by_type["share_true"] = by_type["share_true"].round(3)
    by_type["mean_words"] = by_type["mean_words"].round(1)
    by_type.to_csv(OUT / "summary_by_type.csv", index=False)

    by_topic = (
        data.pivot_table(index="topic", columns="type", values="id", aggfunc="count", observed=True)
        .fillna(0)
        .astype(int)
    )
    by_topic.to_csv(OUT / "summary_by_topic.csv")

    balance = (
        data.pivot_table(index="topic", columns="type", values="label", aggfunc="mean", observed=True)
        .round(2)
    )

    lines = [
        "# Data summary",
        "",
        f"Generated by `scripts/build_dataset.py` from {len(SOURCES)} English CSVs of the "
        "Truth is Universal repository. "
        f"{len(data)} statements, after removing {n_before - len(data) - len(conflicts)} "
        f"exact duplicates and {len(conflicts)} rows whose statement appears with both labels "
        f"({conflicts['statement'].nunique()} distinct statements, mostly in `animal_class_disj` "
        "and `inventors_disj`).",
        "",
        "## By statement type",
        "",
        by_type.to_markdown(index=False),
        "",
        "## Statements per topic and type",
        "",
        by_topic.to_markdown(),
        "",
        "## Share of true statements per topic and type",
        "",
        balance.to_markdown(),
        "",
        "## Points to keep in mind",
        "",
        "- **Comparisons are a different kind of data.** Every comparison statement has "
        "exactly 5 words and is about numbers only, while the other types cover six "
        "knowledge topics. A difference between comparison and the other types can come "
        "from topic or length, not only from sentence structure.",
        "- **Conjunctions and disjunctions are about three times longer** than affirmative "
        "and negated statements.",
        "- **Topic sizes are uneven.** `cities` makes up about half of the affirmative and "
        "negated statements. Sample per topic if the types should be compared on the same "
        "topic mix.",
        "- **Affirmative and negated rows are aligned.** Row *i* of `neg_<topic>.csv` negates "
        "row *i* of `<topic>.csv`, so the pairs share a `group` key.",
        "- **Use `group` for train/test splits** (e.g. scikit-learn `GroupKFold`), so the same "
        "city, number pair or fact never appears on both sides.",
        "- **Conjunctions and disjunctions reuse atomic facts** from the affirmative sets. "
        "That does not matter for within-type probing, but it does for cross-type transfer.",
        "",
    ]
    (DOCS / "data_summary.md").write_text("\n".join(lines), encoding="utf-8")

    print(by_type.to_string(index=False))
    print()
    print(by_topic.to_string())
    print()
    print(f"conflicting duplicate rows: {len(conflicts)}")


if __name__ == "__main__":
    main()
